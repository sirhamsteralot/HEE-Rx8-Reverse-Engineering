#!/usr/bin/env python3
"""Propagate the ignition-key / power-state label addresses to all dumped ROMs.

Reads the per-ROM byte-exact function matches (data/labels/cross_rom_function_matches.tsv,
method unique_exact_bytes, produced by utilities/scripts/cross_rom_match.py) for the
functions labeled by the ignition_power_state pass, plus the ROM-constant entry cells
(u32 at 0x1000 warm-entry pointer, 0x7fff8 recovery-entry pointer, 0x7fffc app pointer),
and writes data/labels/cross_rom/ignition_power_state_addresses.json.

Re-runnable: regenerating must reproduce the committed file byte-for-byte
(tests/test_ignition_power_state.py::test_cross_rom_artifact_regenerates).
Run from the repo root: python utilities/scripts/extract_ignition_power_state_addresses.py
"""

import csv
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
STOCK = ROOT / "submodules" / "Mazda_RX8_PCM_ReverseEngineering" / "Stock_ROMs"
DUMPS = ROOT / "binaries" / "dumps"
MATCHES = ROOT / "data" / "labels" / "cross_rom_function_matches.tsv"
LABELS = ROOT / "data" / "labels" / "60E15120_N3J1E" / "ignition_power_state_labels.json"
OUT = ROOT / "data" / "labels" / "cross_rom" / "ignition_power_state_addresses.json"

BASE_ROM = "60E15120_N3J1E.bin"
BASE_SHA = "a7cd953c2a87af12ee2814a95c958dc23959d352ef9c5e7f82b8ab8952f264f1"

# ROM-constant cells read directly per ROM (u32 big-endian).
ROM_CELLS = {
    "0x00001000": "warm_entry_pointer (u32 at ROM 0x1000; 0x1298 on the base ROM)",
    "0x0007fff8": "recovery_entry_pointer (u32 at ROM 0x7fff8; 0xd204 on the base ROM)",
    "0x0007fffc": "app_pointer (u32 at ROM 0x7fffc; 0x2000 on the base ROM)",
}


def rom_list():
    roms = {}
    for p in sorted(STOCK.glob("*.bin")):
        roms[p.name] = p
    for p in sorted(DUMPS.glob("*.bin")):
        roms["dumps/" + p.name] = p
    return roms


def main():
    labels = json.loads(LABELS.read_text(encoding="utf-8"))
    key_addrs = sorted(labels["function_aliases"].keys())

    matches = {}
    with MATCHES.open(newline="", encoding="utf-8", errors="surrogateescape") as f:
        for r in csv.DictReader(f, delimiter="\t"):
            if r["base_address"] in key_addrs and r["method"] == "unique_exact_bytes":
                matches.setdefault(r["base_address"], {})[r["rom"]] = r["target_address"]

    roms = rom_list()
    rom_info = {}
    cells = {}
    for name, path in roms.items():
        data = path.read_bytes()
        rom_info[name] = {
            "file": path.relative_to(ROOT).as_posix(),
            "sha256": hashlib.sha256(data).hexdigest(),
            "size": len(data),
        }
        cells[name] = {cell: "0x%08x" % int.from_bytes(data[int(cell, 16):int(cell, 16) + 4], "big")
                       for cell in ROM_CELLS}

    out = {
        "pass": "ignition_power_state_labeling",
        "basis": "cross-ROM propagation of data/labels/60E15120_N3J1E/ignition_power_state_labels.json",
        "source": ("Per-ROM function addresses from data/labels/cross_rom_function_matches.tsv "
                   "(unique_exact_bytes, generated by utilities/scripts/cross_rom_match.py); "
                   "ROM-constant cells read directly from each raw ROM (big-endian u32). "
                   "Base ROM 60E15120_N3J1E.bin SHA-256 " + BASE_SHA + "."),
        "base_rom": BASE_ROM,
        "base_sha256": BASE_SHA,
        "key_functions": {
            a: {
                "alias": labels["function_aliases"][a]["alias"],
                "confidence": labels["function_aliases"][a]["confidence"],
                "roms": matches.get(a, {}),
            }
            for a in key_addrs
        },
        "rom_cells": {
            cell: {"meaning": meaning, "per_rom": {name: cells[name][cell] for name in roms}}
            for cell, meaning in ROM_CELLS.items()
        },
        "roms": rom_info,
    }
    OUT.write_text(json.dumps(out, indent=2) + "\n", encoding="utf-8")
    n = sum(len(v["roms"]) for v in out["key_functions"].values())
    print(json.dumps({"roms": len(roms), "key_functions": len(key_addrs), "match_rows": n,
                      "out": OUT.relative_to(ROOT).as_posix()}, indent=2))


if __name__ == "__main__":
    main()
