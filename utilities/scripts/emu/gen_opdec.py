#!/usr/bin/env python3
"""Generate opdec.py (opcode -> (mnemonic, operand tokens)) from a Ghidra-style
disassembly listing. Re-run per ROM and merge to grow coverage:

    python gen_opdec.py <path-to firmware_disassembly.asm> > opdec_new.py

The emulator (sh2e.py) dispatches on this table; branch targets are computed
from the opcode's own displacement bits at runtime, not from the listing.
"""
import re
import sys
from collections import defaultdict


def main(asm_path, out_path):
    m = {}
    for line in open(asm_path, encoding="utf-8", errors="replace"):
        parts = line.split(None, 3)
        if len(parts) < 3 or not re.fullmatch(r"[0-9a-f]{4}", parts[1]):
            continue
        op = int(parts[1], 16)
        mn = parts[2].lstrip("_")  # '_' prefix = delay-slot rendering
        ops = parts[3].strip() if len(parts) > 3 else ""
        if op in m and m[op][0] != mn:
            print(f"warning: conflict at 0x{op:04x}: {m[op][0]} vs {mn}", file=sys.stderr)
        m[op] = (mn, ops)
    with open(out_path, "w", encoding="utf-8") as f:
        f.write('"""Auto-generated by gen_opdec.py from the disassembly - do not edit by hand."""\n')
        f.write("OPMNEM = {\n")
        for op in sorted(m):
            mn, ops = m[op]
            f.write(f"    0x{op:04x}: ({mn!r}, {ops!r}),\n")
        f.write("}\n")
    print(f"wrote {out_path}: {len(m)} opcodes", file=sys.stderr)


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
