"""Biweekly upstream submodule sync + audit for the HEE RX-8 repo.

Checks the three pinned submodules (RX8Defs, Rx8Man,
Mazda_RX8_PCM_ReverseEngineering) against their upstream default branches.
When a submodule moved, the workflow updates the gitlinks on a new branch,
runs an AI-assisted audit of the upstream changes against our own definitions,
labels and docs, and opens a draft PR with the report attached.
"""

from __future__ import annotations

import os
import re
import shutil
import subprocess
import tempfile
from datetime import datetime, timezone
from typing import List, Optional

from pydantic import BaseModel, Field

import mistralai.workflows as workflows

REPO_URL_DEFAULT = "https://github.com/sirhamsteralot/HEE-Rx8-Reverse-Engineering"
GITHUB_TOKEN_ENV = "HEE_GITHUB_TOKEN"
MAX_LOG_COMMITS = 50
MAX_DIFF_STAT_LINES = 40
MAX_DIFF_CHARS = 60_000
MAX_CHANGED_FILES = 400

OUR_AUDIT_PATHS = [
    "data/definitions",
    "data/labels",
    "data/maps",
    "docs/investigations",
    "docs/learnings.md",
    "ROADMAP.md",
]


class SyncInput(BaseModel):
    repo_url: str = REPO_URL_DEFAULT
    base_branch: str = "main"
    branch_prefix: str = "research/upstream-submodule-sync-"
    audit_model: str = "mistral-large-latest"
    dry_run: bool = False


class SubmoduleChange(BaseModel):
    name: str
    path: str
    pinned_sha: str
    latest_sha: str
    new_commit_count: int
    commit_log: str = ""
    diff_stat: str = ""
    changed_files: List[str] = Field(default_factory=list)
    xml_diff: str = ""


class UpstreamCheck(BaseModel):
    repo_dir: str = ""
    changes: List[SubmoduleChange] = Field(default_factory=list)
    up_to_date: List[str] = Field(default_factory=list)


class SyncResult(BaseModel):
    checked: List[str] = Field(default_factory=list)
    changes: List[SubmoduleChange] = Field(default_factory=list)
    audit_report: str = ""
    branch_name: str = ""
    pr_url: str = ""
    pr_number: int = 0
    dry_run: bool = False


def _run(cmd: List[str], cwd: Optional[str] = None) -> str:
    env = dict(os.environ)
    env.setdefault("GIT_LFS_SKIP_SMUDGE", "1")
    proc = subprocess.run(
        cmd, cwd=cwd, env=env, capture_output=True, text=True, timeout=600
    )
    if proc.returncode != 0:
        raise RuntimeError(
            f"command failed ({proc.returncode}): {' '.join(cmd)}\n{proc.stderr[-2000:]}"
        )
    return proc.stdout


def _submodule_names(repo_dir: str) -> List[tuple[str, str]]:
    out = _run(["git", "config", "--file", ".gitmodules", "--get-regexp", r"submodule\..*\.(url|path)"], repo_dir)
    urls: dict[str, str] = {}
    paths: List[str] = []
    for line in out.splitlines():
        key, value = line.split(" ", 1)
        name, _, field = key[len("submodule."):].rpartition(".")
        if field == "url":
            urls[name] = value
        else:
            paths.append(value)
    return [(p, urls[p]) for p in paths]


def _truncate(text: str, limit: int) -> str:
    if len(text) <= limit:
        return text
    return text[:limit] + f"\n... [truncated, {len(text) - limit} chars omitted]"


def branch_name_for(prefix: str, changes: List[SubmoduleChange], when: datetime) -> str:
    short = "-".join(c.latest_sha[:7] for c in changes) or "noop"
    stamp = when.strftime("%Y%m%d")
    return f"{prefix}{stamp}-{short}"


def pr_title_for(changes: List[SubmoduleChange]) -> str:
    parts = [f"{c.name} {c.latest_sha[:7]}" for c in changes]
    return "research: sync submodules to " + ", ".join(parts) + "; audit upstream changes"


def pr_body_for(changes: List[SubmoduleChange], audit_report: str) -> str:
    lines = [
        "## Upstream submodule sync (automated biweekly audit)",
        "",
        "Updated gitlinks:",
        "",
    ]
    for c in changes:
        lines.append(
            f"- **{c.name}**: `{c.pinned_sha[:12]}` → `{c.latest_sha[:12]}` "
            f"({c.new_commit_count} new upstream commits)"
        )
    lines += ["", "## AI-assisted audit vs our definitions / labels / docs", ""]
    lines.append(audit_report or "_No audit report was produced._")
    lines += [
        "",
        "---",
        "_Generated by the `upstream-submodule-sync` Mistral workflow. "
        "Submodules stay read-only context; only gitlinks are updated here._",
    ]
    return "\n".join(lines)


def audit_prompt(changes: List[SubmoduleChange], our_context: str) -> str:
    change_blocks = []
    for c in changes:
        block = [
            f"### {c.name} ({c.new_commit_count} new commits, {c.pinned_sha[:12]} → {c.latest_sha[:12]})",
            "",
            "New commits:",
            "```",
            _truncate(c.commit_log, 8_000),
            "```",
            "",
            "Diff stat:",
            "```",
            _truncate(c.diff_stat, 4_000),
            "```",
        ]
        if c.xml_diff:
            block += [
                "",
                "Changed XML/definition file diff (excerpt):",
                "```diff",
                _truncate(c.xml_diff, 30_000),
                "```",
            ]
        change_blocks.append("\n".join(block))
    return (
        "You are auditing upstream changes to the pinned submodules of the HEE "
        "Mazda RX-8 PCM reverse-engineering repository against that repository's "
        "own work. For each submodule change below:\n\n"
        "1. Summarize what changed upstream (intent, affected areas).\n"
        "2. Identify overlap with our own artifacts: RomRaider/ECUFlash XML "
        "definitions in data/definitions, label/alias TSVs+JSONs in "
        "data/labels, extracted calibration in data/maps, investigation docs "
        "and ROADMAP.md. Flag concrete conflicts (same table/scalar/address "
        "defined differently), stale references, and anything we should adopt.\n"
        "3. Recommend concrete follow-up actions (defs passes to re-run, labels "
        "to re-verify, docs to update, ROADMAP items to open).\n"
        "4. Note risks (breaking changes, renamed files, moved addresses).\n\n"
        "Be specific and cite file paths and addresses/IDs where possible. "
        "Output GitHub-flavored Markdown with a '### Summary', "
        "'### Conflicts & overlap', '### Recommended actions' and '### Risks' "
        "section per submodule.\n\n"
        "Our repository context (file inventory and key docs):\n\n"
        f"{our_context}\n\n"
        "Upstream changes:\n\n" + "\n\n".join(change_blocks)
    )


@workflows.activity()
async def check_upstream(input: SyncInput) -> UpstreamCheck:
    repo_dir = tempfile.mkdtemp(prefix="hee-sync-")
    _run(["git", "clone", "--quiet", "--branch", input.base_branch, input.repo_url, repo_dir])
    _run(["git", "submodule", "update", "--init", "--quiet"], repo_dir)
    check = UpstreamCheck(repo_dir=repo_dir)
    for path, url in _submodule_names(repo_dir):
        sub_dir = os.path.join(repo_dir, path)
        pinned = _run(["git", "ls-tree", "HEAD", path], repo_dir).split()[2]
        _run(["git", "fetch", "--quiet", "origin"], sub_dir)
        latest = _run(["git", "rev-parse", "FETCH_HEAD"], sub_dir).strip()
        if pinned == latest:
            check.up_to_date.append(path)
            continue
        count = int(_run(["git", "rev-list", "--count", f"{pinned}..{latest}"], sub_dir).strip() or "0")
        log = _run(["git", "log", "--oneline", "--no-decorate", "-n", str(MAX_LOG_COMMITS), f"{pinned}..{latest}"], sub_dir)
        stat = _run(["git", "diff", "--stat", f"{pinned}..{latest}"], sub_dir)
        stat_tail = "\n".join(stat.splitlines()[-MAX_DIFF_STAT_LINES:])
        files = [
            line[len(path) + 1:]
            for line in _run(["git", "diff", "--name-only", f"{pinned}..{latest}"], sub_dir).splitlines()
            if line.startswith(path + "/")
        ][:MAX_CHANGED_FILES]
        xml_files = [f for f in files if f.endswith((".xml", ".md", ".txt", ".csv"))]
        xml_diff = ""
        if xml_files:
            xml_diff = _run(["git", "diff", f"{pinned}..{latest}", "--"] + xml_files, sub_dir)
        check.changes.append(
            SubmoduleChange(
                name=os.path.basename(path),
                path=path,
                pinned_sha=pinned,
                latest_sha=latest,
                new_commit_count=count,
                commit_log=log,
                diff_stat=stat_tail,
                changed_files=files,
                xml_diff=xml_diff,
            )
        )
    return check


@workflows.activity()
async def collect_our_context(check: UpstreamCheck) -> str:
    repo_dir = check.repo_dir
    parts = []
    for rel in OUR_AUDIT_PATHS:
        target = os.path.join(repo_dir, rel)
        if os.path.isfile(target):
            with open(target, "r", errors="replace") as fh:
                parts.append(f"#### {rel} (excerpt)\n```\n{_truncate(fh.read(), 6_000)}\n```")
        elif os.path.isdir(target):
            listing = []
            for root, _dirs, names in os.walk(target):
                for n in sorted(names):
                    if not n.endswith((".xml", ".tsv", ".json", ".md", ".csv")):
                        continue
                    listing.append(os.path.relpath(os.path.join(root, n), repo_dir))
                    if len(listing) >= 200:
                        break
            parts.append(f"#### Files under {rel}\n```\n" + "\n".join(listing) + "\n```")
    return "\n\n".join(parts)


@workflows.activity()
async def ai_audit(input: SyncInput, changes: List[SubmoduleChange], our_context: str) -> str:
    if not changes:
        return "No upstream changes to audit."
    from mistralai.client import Mistral

    client = Mistral()
    prompt = audit_prompt(changes, our_context)
    response = client.chat.complete(
        model=input.audit_model,
        messages=[{"role": "user", "content": prompt}],
    )
    content = response.choices[0].message.content
    if isinstance(content, list):
        content = "".join(part.text for part in content)
    return content or ""


@workflows.activity()
async def push_branch_and_open_pr(input: SyncInput, check: UpstreamCheck, changes: List[SubmoduleChange], audit_report: str) -> SyncResult:
    result = SyncResult(dry_run=input.dry_run)
    if input.dry_run:
        return result
    token = os.environ.get(GITHUB_TOKEN_ENV, "") or os.environ.get(GITHUB_TOKEN_ENV.lower(), "")
    if not token:
        raise RuntimeError(
            f"Missing {GITHUB_TOKEN_ENV}: bind the workspace secret holding a "
            "GitHub PAT (repo contents + pull requests write) to the deployment."
        )
    repo_dir = check.repo_dir
    _run(["git", "submodule", "update", "--remote", "--quiet"], repo_dir)
    _run(["git", "config", "user.name", "hee-upstream-sync-bot"], repo_dir)
    _run(["git", "config", "user.email", "noreply@users.noreply.github.com"], repo_dir)
    branch = branch_name_for(input.branch_prefix, changes, datetime.now(timezone.utc))
    _run(["git", "checkout", "-q", "-b", branch], repo_dir)
    _run(["git", "add", ".gitmodules", "submodules"], repo_dir)
    _run(["git", "commit", "-q", "-m", pr_title_for(changes)], repo_dir)
    owner_repo = re.sub(r"^https://github\.com/", "", input.repo_url).removesuffix(".git")
    push_url = f"https://x-access-token:{token}@github.com/{owner_repo}.git"
    _run(["git", "push", "--quiet", push_url, f"HEAD:refs/heads/{branch}"], repo_dir)
    result.branch_name = branch

    import httpx

    api = f"https://api.github.com/repos/{owner_repo}/pulls"
    pr_body = pr_body_for(changes, audit_report)
    with httpx.Client(timeout=60) as http:
        resp = http.post(
            api,
            headers={
                "Authorization": f"Bearer {token}",
                "Accept": "application/vnd.github+json",
                "X-GitHub-Api-Version": "2022-11-28",
            },
            json={
                "title": pr_title_for(changes),
                "body": pr_body,
                "head": branch,
                "base": input.base_branch,
                "draft": True,
            },
        )
        if resp.status_code == 422 and "A pull request already exists" in resp.text:
            q = http.get(
                f"https://api.github.com/repos/{owner_repo}/pulls",
                headers={"Authorization": f"Bearer {token}"},
                params={"head": f"{owner_repo.split('/')[0]}:{branch}", "state": "open"},
            )
            if q.status_code == 200 and q.json():
                pr = q.json()[0]
                result.pr_url, result.pr_number = pr["html_url"], pr["number"]
        else:
            resp.raise_for_status()
            pr = resp.json()
            result.pr_url, result.pr_number = pr["html_url"], pr["number"]
    return result


@workflows.activity()
async def cleanup_repo(check: UpstreamCheck) -> None:
    try:
        shutil.rmtree(check.repo_dir, ignore_errors=True)
    finally:
        pass


@workflows.workflow.define(
    name="upstream-submodule-sync",
    workflow_display_name="Upstream submodule sync & audit",
    workflow_description=(
        "Biweekly: pull new versions of all submodules, and when upstream "
        "moved, update the gitlinks and audit the upstream changes against our "
        "own definitions, labels and docs in a draft PR."
    ),
)
class UpstreamSubmoduleSyncWorkflow:
    @workflows.workflow.entrypoint
    async def run(self, input: SyncInput) -> SyncResult:
        check = await check_upstream(input)
        if not check.changes:
            await cleanup_repo(check)
            return SyncResult(checked=check.up_to_date)
        our_context = await collect_our_context(check)
        audit_report = await ai_audit(input, check.changes, our_context)
        result = await push_branch_and_open_pr(input, check, check.changes, audit_report)
        result.checked = check.up_to_date
        result.changes = check.changes
        result.audit_report = audit_report
        await cleanup_repo(check)
        return result
